export function calculateSpecialHitDamage(
  attackerSpec: ArchetypeSpec,
  defenderSpec: ArchetypeSpec
): { totalDamage: number; perHitDamage: number; underdogBonusPct: number } {
  let bonusMultiplier = 1.0;
  let underdogBonusPct = 0;

  // Pawn's unique Underdog Valor scaling: +14% per point of enemy tactical value above 1
  if (attackerSpec.type === 'p' && defenderSpec.tacticalValue > 1) {
    underdogBonusPct = (defenderSpec.tacticalValue - 1) * 14;
    bonusMultiplier = 1 + underdogBonusPct / 100;
  }

  const totalDamage = Math.round(attackerSpec.special.baseDamage * bonusMultiplier);
  const perHitDamage = Math.max(4, Math.round(totalDamage / attackerSpec.special.hits));

  return { totalDamage, perHitDamage, underdogBonusPct };
}
